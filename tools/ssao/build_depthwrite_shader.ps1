# Builds the BS2-patched stock depthwrite pixel shaders (ps20b + ps30, all 4 combos) so the stock DepthWrite shader
# loads them from the mod's shaders\fxc. Claude for Isa, 16 Nov 2026 (SSAO v3).
param([Parameter(Mandatory=$true)][string]$SdkBin, [Parameter(Mandatory=$true)][string]$Worktree)
$ErrorActionPreference = 'Stop'
$GameDir = (Resolve-Path -LiteralPath "$Worktree\sp\game\mod_episodic").Path
$compiler = Join-Path $SdkBin 'shadercompile.exe'
foreach ($v in @(@('depthwrite_ps20b','/Tps_2_b /DSHADER_MODEL_PS_2_B=1'), @('depthwrite_ps30','/Tps_3_0 /DSHADER_MODEL_PS_3_0=1'))) {
$name = $v[0]; $src = 'depthwrite_ps2x.fxc'
$stage = Join-Path $Worktree "tools\ssao\shader-build\$name"
Remove-Item -Recurse -Force $stage -ea 0
New-Item -ItemType Directory -Force -Path (Join-Path $stage 'shaders\fxc') | Out-Null
Copy-Item -LiteralPath "$Worktree\sp\src\materialsystem\stdshaders\$src" -Destination $stage
Copy-Item -LiteralPath "$Worktree\sp\src\dx9sdk\utilities\dx_proxy.dll" -Destination $stage
@"
**** generated by BS2 build_depthwrite_shader.ps1 ****
#BEGIN $name
$src
#DEFINES-D:
ALPHACLIP=0..1
#DEFINES-S:
COLOR_DEPTH=0..1
#SKIP:
0
#COMMAND:
fxc.exe /DTOTALSHADERCOMBOS=4 /DCENTROIDMASK=0 /DNUMDYNAMICCOMBOS=2 /DFLAGS=0x0
$($v[1]) /nologo /Foshader.o $src>output.txt 2>&1
#END
**** end ****
"@ | Set-Content -LiteralPath (Join-Path $stage 'filelist.txt') -Encoding ascii
@($src,'dx_proxy.dll',"$SdkBin\shadercompile.exe", "$SdkBin\shadercompile_dll.dll", "$SdkBin\tier0.dll", "$SdkBin\vstdlib.dll") | Set-Content -LiteralPath (Join-Path $stage 'uniquefilestocopy.txt') -Encoding ascii
$started = Get-Date
Push-Location $stage
try { & $compiler -nompi -nop4 -game $GameDir -shaderpath $stage -allowdebug; if ($LASTEXITCODE -ne 0) { throw "shadercompile failed: $LASTEXITCODE" } } finally { Pop-Location }
$compiled = Join-Path $stage "shaders\fxc\$name.vcs"
if (!(Test-Path -LiteralPath $compiled) -or (Get-Item -LiteralPath $compiled).LastWriteTime -lt $started) { throw "No fresh VCS for $name" }
Copy-Item -LiteralPath $compiled -Destination "$GameDir\shaders\fxc"
Write-Output "Compiled $name.vcs ($((Get-Item $compiled).Length) bytes)"
}
